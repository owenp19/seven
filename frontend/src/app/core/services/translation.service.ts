const DICTIONARIES: Record<Language, Record<TranslationKey, string>> = { es, en, pt };

const STORAGE_KEY = 'seven_language';
const DEFAULT_LANGUAGE: Language = 'es';

/**
 * TranslationService
 *
 * Idioma de la interfaz en ES/EN/PT sin login: la preferencia vive en
 * `localStorage`, igual que el Install ID, así que sobrevive al cierre de la
 * app sin pedir ningún dato al usuario.
 *
 * El idioma es un `signal`, de modo que las plantillas que llaman a `t()`
 * directamente se re-pintan solas al cambiar; el pipe `| t` cubre los casos
 * donde conviene resolver la clave desde un `@for` o un atributo.
 */
@Injectable({ providedIn: 'root' })
export class TranslationService {
  readonly languages: readonly LanguageOption[] = [
    { code: 'es', short: 'ES', name: 'Español' },
    { code: 'en', short: 'EN', name: 'English' },
    { code: 'pt', short: 'PT', name: 'Português' },
  ];

  readonly language = signal<Language>(TranslationService.readStoredLanguage());

  constructor() {
    this.applyDocumentLanguage();
  }

  setLanguage(code: Language): void {
    if (this.language() === code) {
      return;
    }

    this.language.set(code);
    localStorage.setItem(STORAGE_KEY, code);
    this.applyDocumentLanguage();
  }

  isActive(code: Language): boolean {
    return this.language() === code;
  }

  /**
   * Traduce `key` al idioma activo. Los placeholders `{algo}` se rellenan
   * con `params`; si falta un parámetro se devuelve la clave de la traducción
   * original para que el hueco sea visible en lugar de romperse la pantalla.
   */
  t(key: TranslationKey, params?: Record<string, string | number>): string {
    const template = DICTIONARIES[this.language()][key] ?? DICTIONARIES[DEFAULT_LANGUAGE][key] ?? key;

    if (!params) {
      return template;
    }

    return template.replace(/\{(\w+)\}/g, (match, name: string) =>
      name in params ? String(params[name]) : match,
    );
  }

  private applyDocumentLanguage(): void {
    if (typeof document === 'undefined') {
      return;
    }

    document.documentElement.lang = this.language();
  }

  private static readStoredLanguage(): Language {
    const stored = localStorage.getItem(STORAGE_KEY);

    if (stored === 'es' || stored === 'en' || stored === 'pt') {
      return stored;
    }

    return DEFAULT_LANGUAGE;
  }
}
